def main():
    path = DATA_DIR / "穴位表.csv"
    with open(path, encoding="utf-8-sig", newline="") as f:
        reader = csv.DictReader(f)
        fields = reader.fieldnames
        rows = list(reader)

    existing = {r["穴名"].strip() for r in rows}
    new_rows = []
    for (name, code, region, zone, teas, loc, needle, kw, dy, note, page, md) in POINTS:
        if name in existing:
            print(f"⚠ {name} 已存在，跳過")
            continue
        row = {k: "" for k in fields}
        row.update({
            "穴名": name, "部位代碼": code, "部位": region, "身體分區": zone,
            "穴號": teas, "取穴定位": tw(loc), "針法": tw(needle),
            "主治關鍵字": tw(kw), "董楊思維": tw(dy), "備註": tw(note),
            "詳細筆記": f"notes/{name}.md", "頁碼": page,
        })
        new_rows.append(row)
        (DATA_DIR / "notes" / f"{name}.md").write_text(tw(md), encoding="utf-8")

    # 插在各部位區塊尾端
    out = []
    pending = {}
    for r in new_rows:
        pending.setdefault(r["部位"], []).append(r)
    for i, r in enumerate(rows):
        out.append(r)
        region = r["部位"]
        is_last = i + 1 == len(rows) or rows[i + 1]["部位"] != region
        if is_last and region in pending:
            out.extend(pending.pop(region))
    for rest in pending.values():  # 不該發生，保險
        out.extend(rest)

    with open(path, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        w.writerows(out)
    print(f"新增 {len(new_rows)} 穴，穴位表共 {len(out)} 列")
    for r in new_rows:
        print(f"  {r['穴號']:8s} {r['穴名']}（{r['部位']}）")


if __name__ == "__main__":
    main()
