# 一名雙穴：指五金 / 指千金 共用 11.08
DUAL_1108 = {"指五金", "指千金", "指五金、指千金"}

# 異體字正規化（兩邊都轉成同一形）
VARIANTS = str.maketrans("姊污崑崙裡博", "姐汙昆侖里搏")

# TEAS 編號前綴 → 部位代碼（用來報告錯置，不自動搬移）
PREFIX_REGION = {
    "11": "一一", "22": "二二", "33": "三三", "44": "四四", "55": "五五",
    "66": "六六", "77": "七七", "88": "八八", "99": "九九",
    "1010": "十十", "1111": "背腰", "CA": "胸腹", "A": "增補",
}

# 身體分區改名（部位代碼 → 新名稱）
NEW_ZONES = {
    "四四": "上臂穴位", "五五": "腳趾穴位", "六六": "腳掌穴位",
    "七七": "小腿穴位", "八八": "大腿穴位", "十十": "頭面穴位",
}


def norm(name):
    n = name.replace(" ", "").replace("二十三", "23").translate(VARIANTS)
    if n.endswith("穴") and len(n) > 2:
        n = n[:-1]
    return n


def write_csv(path, rows, fieldnames):
    with open(path, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fieldnames)
        w.writeheader()
        w.writerows(rows)


def main():
    name_to_code = {}
    for code, name in TEAS.items():
        name_to_code[norm(name)] = code
    for n in DUAL_1108:
        name_to_code[norm(n)] = "11.08"

    # ── 1+2. 穴位表：穴號 + 身體分區 ──
    path = DATA_DIR / "穴位表.csv"
    with open(path, encoding="utf-8-sig", newline="") as f:
        reader = csv.DictReader(f)
        fields = reader.fieldnames
        rows = list(reader)

    matched, unmatched, mismatched = 0, [], []
    for r in rows:
        code = name_to_code.get(norm(r["穴名"].strip()), "")
        r["穴號"] = code
        if code:
            matched += 1
            prefix = code.split(".")[0]
            expect = PREFIX_REGION.get(prefix, "")
            if expect and expect != r["部位代碼"]:
                mismatched.append((r["穴名"], code, r["部位代碼"], expect))
        else:
            unmatched.append((r["穴名"], r["部位"]))
        if r["部位代碼"] in NEW_ZONES:
            r["身體分區"] = NEW_ZONES[r["部位代碼"]]
    write_csv(path, rows, fields)
    print(f"穴位表：{matched} 筆配上 TEAS 編號，{len(unmatched)} 筆留空白")

    # ── 2. 部位表 ──
    path = DATA_DIR / "部位表.csv"
    with open(path, encoding="utf-8-sig", newline="") as f:
        reader = csv.DictReader(f)
        fields = reader.fieldnames
        rows = list(reader)
    for r in rows:
        if r["部位代碼"] in NEW_ZONES:
            r["身體分區"] = NEW_ZONES[r["部位代碼"]]
    write_csv(path, rows, fields)
    print("部位表：身體分區已更新")

    # ── 3. 對針表：清掉不存在的圖片路徑 ──
    path = DATA_DIR / "對針表.csv"
    with open(path, encoding="utf-8-sig", newline="") as f:
        reader = csv.DictReader(f)
        fields = reader.fieldnames
        rows = list(reader)
    cleared = 0
    for r in rows:
        p = r["圖片"].strip()
        if p and not (DATA_DIR / p).exists():
            r["圖片"] = ""
            cleared += 1
    write_csv(path, rows, fields)
    print(f"對針表：清除 {cleared} 筆不存在的圖片路徑")

    print("\n── 比對不到 TEAS 編號的穴名（穴號留空白）──")
    for name, region in unmatched:
        print(f"  {region}  {name!r}")
    print("\n── 部位與 TEAS 編號前綴不一致（僅報告，未搬移）──")
    for name, code, db_region, expect in mismatched:
        print(f"  {name}（{code}）：資料在「{db_region}」，編號屬「{expect}」")

    db_norms = {norm(r["穴名"].strip()) for r in
                csv.DictReader(open(DATA_DIR / "穴位表.csv", encoding="utf-8-sig"))}
    missing = [f"{c} {n}" for c, n in sorted(TEAS.items()) if norm(n) not in db_norms]
    print("\n── TEAS 索引中資料庫沒有的穴位 ──")
    for m in missing:
        print(f"  {m}")


if __name__ == "__main__":
    main()
